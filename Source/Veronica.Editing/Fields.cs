using System.Reflection;
using Keen.VRage.Library.Definitions;
using Keen.VRage.Library.Localization;
using Keen.VRage.Library.Mathematics;
using Keen.VRage.Library.Serialization;
using Keen.VRage.Library.UI.Attributes;
using Keen.VRage.Library.UI.PropertyInspector;
using Keen.VRage.Library.UI.PropertyInspector.Visibility;
using Keen.VRage.Library.Utils;
using Keen.VRage.Library.Utils.Assets;
using Keen.VRage.UI.Shared.ObjectInspector.Strategies;

namespace Veronica.Editing;

public static class Fields
{
    public const int MaxInlineFields = 4;

    private static readonly DefaultObjectInspectorVisibilityStrategy Visibility = new(null);

    // Fields the inspector hides because the Editor edits them in a dedicated window; without them the
    // model cannot see what the definition is made of.
    private static readonly HashSet<string> ForceShown =
    [
        "ParticleEffectDefinition.ParticleEmitters",
        "ParticleEffectDefinition.ParticleLight",
    ];

    // What the Property Inspector would show.
    public static bool IsVisible(MemberReference member)
    {
        if (member.IsCollectionItem)
            return true;

        try
        {
            if (IsForceShown(member))
                return true;
            // Selection mirrors are force-generated by the inspector but read as empty structs outside it.
            if (member.GetMemberAttribute<SelectedItemOfAttribute>() != null)
                return false;
            // Euler hints are the inspector's degrees cache of a quaternion; transforms show them as Euler.
            if (member.GetMemberAttribute<EulerHintAttribute>() != null)
                return false;
            // A colour's packed value is its R, G, B and A again; a model wrote both and got the packing wrong.
            if (IsPackedColour(member))
                return false;
            return Visibility.ShouldGenerate(member);
        }
        catch (Exception)
        {
            return false;
        }
    }

    private static bool IsPackedColour(MemberReference member)
    {
        if (member.Name != "PackedValue")
            return false;
        Type owner = member.GetParent().CurrentMemberType;
        // Only where the inspector shows the channels; ColorSRGBPremultiplied's are hidden, so its packed value is all there is.
        return owner.IsValueType && new[] { "R", "G", "B", "A" }.All(c => owner.GetProperty(c)?.GetCustomAttribute<ForceShowInInspectorAttribute>() != null);
    }

    // Definitions are edited as their object builders, which share the definition's field names.
    private static bool IsForceShown(MemberReference member)
    {
        string owner = member.GetParent().CurrentMemberType.Name;
        if (owner.EndsWith("ObjectBuilder"))
            owner = owner[..^"ObjectBuilder".Length];
        return ForceShown.Contains($"{owner}.{member.Name}");
    }

    // Writable the way the inspector allows: a setter, no [ReadOnlyInInspector], and no read-only struct
    // above it, since a struct field is written back through its parent.
    public static bool IsWritable(MemberReference member)
    {
        if (member.IsRoot || member.IsReadOnly || member.GetMemberAttribute<ReadOnlyInInspectorAttribute>() != null)
            return false;

        for (var parent = member.GetParent(); !parent.IsRoot; parent = parent.GetParent())
        {
            if (parent.MemberKind == MemberValueKind.Value && ValueType(parent).IsValueType && parent.IsReadOnly)
                return false;
        }
        return true;
    }

    // Read-only values in a dump are computed (a vector's length, a sum). A read-only object is still
    // there to be edited through its fields.
    public static bool IsComputed(MemberReference member) =>
        member.MemberKind == MemberValueKind.Value
        && !IsWritable(member)
        && (IsScalar(ValueType(member)) || ValueType(member).IsValueType);

    public static List<MemberReference> VisibleMembers(MemberReference parent)
    {
        try
        {
            return parent.Members.Where(IsVisible).ToList();
        }
        catch (Exception)
        {
            return [];
        }
    }

    public static Type ValueType(MemberReference member)
    {
        Type declared = member.DeclaredMemberType;
        return Nullable.GetUnderlyingType(declared) ?? declared;
    }

    public static bool IsScalar(Type type) =>
        type.IsPrimitive
        || type.IsEnum
        || type == typeof(string)
        || type == typeof(decimal)
        || type == typeof(Guid)
        || type == typeof(StringId)
        || type == typeof(LocKey)
        || typeof(IResourceHandle).IsAssignableFrom(type)
        || typeof(Definition).IsAssignableFrom(type)
        || (type.IsValueType && Values.HasParse(type));

    public static ReferenceSpec? GetReference(MemberReference member)
    {
        Type type = ValueType(member);
        var allowed = member.GetMemberAttribute<AllowDefinitionTypeAttribute>()?.DefinitionType;
        IReadOnlyList<Type> extra = allowed is null ? [] : [allowed];

        if (typeof(Definition).IsAssignableFrom(type))
            return new ReferenceSpec(member, ReferenceKind.Definition, [type, .. extra], []);

        if (typeof(IResourceHandle).IsAssignableFrom(type))
            return new ReferenceSpec(member, ReferenceKind.Handle, extra, AllowedExtensions(type));

        if (type == typeof(Guid) && member.GetMemberAttribute<AssetReferenceAttribute>() != null)
            return new ReferenceSpec(member, ReferenceKind.AssetGuid, extra, []);

        return null;
    }

    // Mirrors the inspector: a typed handle accepts the file types its asset declares.
    private static IReadOnlyList<string> AllowedExtensions(Type handleType)
    {
        if (!handleType.IsGenericType || handleType.GenericTypeArguments is not [var assetType])
            return [];
        if (!AssetIndexer.Instance.OverridenAssets.TryGetValue(assetType, out var asset))
            return [];

        var extensions = new List<string>();
        foreach (var supported in asset.SupportedTypes)
            extensions.Add(supported.Extension.ToLowerInvariant().Trim('.'));
        return extensions;
    }

    // Value types whose visible writable fields are at most four plain scalars print on one line.
    public static bool TryGetInlineFields(MemberReference member, out List<MemberReference> fields)
    {
        fields = [];
        if (member.MemberKind != MemberValueKind.Value || !ValueType(member).IsValueType || IsScalar(ValueType(member)))
            return false;

        try
        {
            if (member.GetValue<object?>() is null)
                return false;
        }
        catch (Exception)
        {
            return false;
        }

        foreach (var child in VisibleMembers(member))
        {
            if (child.IsReadOnly)
                continue;
            if (child.MemberKind != MemberValueKind.Value || !IsScalar(ValueType(child)) || GetReference(child) != null)
                return false;
            fields.Add(child);
        }

        return fields.Count is > 0 and <= MaxInlineFields;
    }

    // A transform is a value type whose visible writable fields are an inline position and a quaternion.
    public static bool TryGetTransform(MemberReference member, out MemberReference position, out MemberReference orientation)
    {
        position = default;
        orientation = default;
        if (member.MemberKind != MemberValueKind.Value || !ValueType(member).IsValueType || IsScalar(ValueType(member)))
            return false;

        try
        {
            if (member.GetValue<object?>() is null)
                return false;
        }
        catch (Exception)
        {
            return false;
        }

        var children = VisibleMembers(member).Where(c => !c.IsReadOnly).ToList();
        // A wrapper of one transform and its (hidden) Euler hint, such as a dummy's Transform, is that transform.
        if (children.Count == 1 && HasEulerHint(member))
            return TryGetTransform(children[0], out position, out orientation);
        if (children.Count != 2)
            return false;
        foreach (var child in children)
        {
            if (child.MemberKind != MemberValueKind.Value)
                return false;
            if (ValueType(child) == typeof(Quaternion))
                orientation = child;
            else if (TryGetInlineFields(child, out _))
                position = child;
        }
        return !position.IsDefault && !orientation.IsDefault;
    }

    private static bool HasEulerHint(MemberReference member)
    {
        try
        {
            return member.Members.Any(m => m.GetMemberAttribute<EulerHintAttribute>() != null);
        }
        catch (Exception)
        {
            return false;
        }
    }

    public static string TypeLabel(Type declared)
    {
        Type? underlying = Nullable.GetUnderlyingType(declared);
        if (underlying != null)
            return TypeLabel(underlying) + "?";
        if (Keywords.TryGetValue(declared, out var keyword))
            return keyword;
        if (declared.IsGenericType)
        {
            string name = declared.Name[..declared.Name.IndexOf('`')];
            return $"{name}<{string.Join(", ", declared.GenericTypeArguments.Select(TypeLabel))}>";
        }
        return declared.Name;
    }

    private static readonly Dictionary<Type, string> Keywords = new()
    {
        [typeof(bool)] = "bool",
        [typeof(byte)] = "byte",
        [typeof(sbyte)] = "sbyte",
        [typeof(short)] = "short",
        [typeof(ushort)] = "ushort",
        [typeof(int)] = "int",
        [typeof(uint)] = "uint",
        [typeof(long)] = "long",
        [typeof(ulong)] = "ulong",
        [typeof(float)] = "float",
        [typeof(double)] = "double",
        [typeof(decimal)] = "decimal",
        [typeof(string)] = "string",
        [typeof(char)] = "char",
    };

    public static Type? ElementType(Type collection)
    {
        foreach (var candidate in collection.GetInterfaces().Prepend(collection))
        {
            if (candidate.IsGenericType && candidate.GetGenericTypeDefinition() == typeof(IList<>))
                return candidate.GenericTypeArguments[0];
        }
        return null;
    }

    public static (Type Key, Type Value)? DictionaryTypes(Type dictionary)
    {
        foreach (var candidate in dictionary.GetInterfaces().Prepend(dictionary))
        {
            if (!candidate.IsGenericType)
                continue;
            var definition = candidate.GetGenericTypeDefinition();
            if (definition == typeof(IDictionary<,>) || definition == typeof(IReadOnlyDictionary<,>))
                return (candidate.GenericTypeArguments[0], candidate.GenericTypeArguments[1]);
        }
        return null;
    }

    // Immutable mergeable lists are edited through the list they wrap, as the inspector does.
    public static MemberReference Unwrap(MemberReference member) => member.TryGetImmutableMergeableListData() ?? member;

    // A mergeable list keys its elements with new ids itself; other keyed lists need a key with every element.
    public static bool GeneratesOwnKeys(Type collection)
    {
        for (Type? t = collection; t != null; t = t.BaseType)
        {
            if (t.IsGenericType && t.GetGenericTypeDefinition() == typeof(Keen.VRage.Library.Collections.MergeableList<>))
                return true;
        }
        return false;
    }

    // Key type of a keyed list (KeyedCollection<TKey, TItem>), or null for a plain list.
    public static Type? KeyedListKeyType(Type collection)
    {
        for (Type? t = collection; t != null; t = t.BaseType)
        {
            if (t.IsGenericType && t.GetGenericTypeDefinition() == typeof(Keen.VRage.Library.Collections.KeyedCollection<,>))
                return t.GenericTypeArguments[0];
        }
        return null;
    }

    public static string KeyText(object? key) => key switch
    {
        null => "null",
        string s => s,
        IFormattable f => f.ToString(null, System.Globalization.CultureInfo.InvariantCulture),
        _ => key.ToString() ?? "null",
    };

    internal static bool HasPublicStaticMethod(Type type, string name, params Type[] parameters) =>
        type.GetMethod(name, BindingFlags.Public | BindingFlags.Static, parameters) != null;
}
